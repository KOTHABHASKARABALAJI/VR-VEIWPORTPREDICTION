"""
Script: extract_video_metadata.py
Project: Machine Learning-Based Viewport Tile Prediction and Adaptive Quality Allocation for 360° Video Streaming

Purpose:
    Parses the 20 technical FFprobe JSON files in the 'SRC_info/' folder, extracts essential video and
    audio encoding characteristics (width, height, resolution, frame rate, duration, container, codecs,
    file size, and bitrates), compiles them into a structured tabular catalog, and exports the data
    to 'video_metadata.csv'.

Role in Workflow:
    Stage 2 (Video Metadata Extraction): Documents the technical specifications of all 20 source
    panoramas in the AVTrack360 dataset. Understanding video resolution (e.g., 3840x1920) and duration
    (~30 seconds) is essential for future spatial equirectangular tiling and tile bitrate allocation.
"""

# Standard library module to parse nested JSON streams generated by FFprobe
import json

# Standard library module for object-oriented filesystem paths
from pathlib import Path

# Third-party tabular data processing library for DataFrame manipulation and CSV export
import pandas as pd


def extract_metadata():
    """
    Extracts video and audio stream attributes from SRC_info/*.json for all 20 videos,
    compiles a structured DataFrame, exports to 'video_metadata.csv', and prints completeness diagnostics.

    Parameters:
        None

    Returns:
        None: Exports 'video_metadata.csv' to the project root and prints summary tables to console.
    """
    # Dynamically determine the project root directory (two levels up from src/preprocessing)
    project_root = Path(__file__).resolve().parents[2]

    # Define paths for the input metadata directory and output consolidated CSV
    src_info_dir = project_root / "data" / "raw" / "SRC_info"
    output_csv = project_root / "data" / "processed" / "video_metadata.csv"
    output_csv.parent.mkdir(parents=True, exist_ok=True)

    # Prepare files 1.json to 20.json in strict numerical order (corresponding to videos 1.mp4 through 20.mp4)
    json_files = [src_info_dir / f"{i}.json" for i in range(1, 21)]

    # In-memory storage list for extracted video metadata dictionaries
    records = []

    # Iterate through each video metadata JSON file
    for json_path in json_files:
        video_id = f"{json_path.stem}.mp4"
        
        # Verify file presence before opening
        if not json_path.exists():
            print(f"[WARNING] File not found: {json_path}")
            continue

        # Load FFprobe JSON content
        with open(json_path, "r", encoding="utf-8") as f:
            data = json.load(f)

        # Retrieve the 'streams' array and the top-level 'format' container dictionary
        streams = data.get("streams", [])
        fmt = data.get("format", {})

        # Find the video stream and audio stream using Python generator expressions
        # Returns an empty dictionary {} as a fallback if the stream type is not found
        video_stream = next((s for s in streams if s.get("codec_type") == "video"), {})
        audio_stream = next((s for s in streams if s.get("codec_type") == "audio"), {})

        # Extract video stream dimensions and format
        width = video_stream.get("width")
        height = video_stream.get("height")
        resolution = f"{width}x{height}" if width is not None and height is not None else None
        
        display_aspect_ratio = video_stream.get("display_aspect_ratio") # e.g., 2:1 or 16:9
        r_frame_rate = video_stream.get("r_frame_rate")                 # Real base frame rate (e.g., "30/1")
        avg_frame_rate = video_stream.get("avg_frame_rate")             # Average frame rate (e.g., "30/1")
        duration = video_stream.get("duration")                         # Duration in seconds (e.g., "30.033333")
        nb_frames = video_stream.get("nb_frames")                       # Total video frames (e.g., 901 frames)
        video_codec = video_stream.get("codec_name")                     # Video compression codec (e.g., "rawvideo")
        pixel_format = video_stream.get("pix_fmt")                       # Chroma subsampling format (e.g., "yuv420p")

        # Extract container format and bitrate metrics
        container_format = fmt.get("format_name")                       # Container format (e.g., "avi")
        file_size = fmt.get("size")                                     # File size in bytes (e.g., 9.9 GB for uncompressed)
        overall_bitrate = fmt.get("bit_rate")                           # Total stream bitrate in bits per second
        
        # Extract audio stream details if an audio track exists
        audio_codec = audio_stream.get("codec_name") if audio_stream else None
        audio_bitrate = audio_stream.get("bit_rate") if audio_stream else None

        # Append structured dictionary record
        records.append({
            "video_id": video_id,
            "width": width,
            "height": height,
            "resolution": resolution,
            "display_aspect_ratio": display_aspect_ratio,
            "r_frame_rate": r_frame_rate,
            "avg_frame_rate": avg_frame_rate,
            "duration": duration,
            "nb_frames": nb_frames,
            "video_codec": video_codec,
            "pixel_format": pixel_format,
            "container_format": container_format,
            "file_size": file_size,
            "overall_bitrate": overall_bitrate,
            "audio_codec": audio_codec,
            "audio_bitrate": audio_bitrate
        })

    # Construct tabular pandas DataFrame from all video records
    df = pd.DataFrame(records)
    
    # Save CSV catalog to disk without row index numbers
    df.to_csv(output_csv, index=False, encoding="utf-8")
    print(f"[SUCCESS] Metadata extracted and saved to: {output_csv.resolve()}\n")

    # Print full 20-row table to console with expanded display settings
    print("=" * 120)
    print("                                      VIDEO METADATA TABLE (20 ROWS)                                      ")
    print("=" * 120)
    pd.set_option("display.max_columns", None) # Display all 16 columns without truncation
    pd.set_option("display.max_rows", None)    # Display all 20 rows
    pd.set_option("display.width", 1000)       # Set wide terminal print width
    print(df.to_string(index=False))
    print("=" * 120)

    # Report missing fields analysis
    print("\n" + "=" * 60)
    print("                      MISSING FIELDS REPORT                      ")
    print("=" * 60)
    missing_counts = df.isna().sum()
    total_rows = len(df)
    
    has_missing = False
    for col, count in missing_counts.items():
        if count > 0:
            has_missing = True
            missing_videos = df[df[col].isna()]["video_id"].tolist()
            print(f"  - Column '{col}': {count}/{total_rows} missing values (Missing in: {', '.join(missing_videos)})")
        else:
            print(f"  - Column '{col}': 0 missing values (100% complete)")

    # Provide contextual explanation for any missing values
    if not has_missing:
        print("\n[INFO] All columns are 100% complete with 0 missing fields across all 20 videos.")
    else:
        print("\n[INFO] Note: Missing audio_codec or audio_bitrate indicates videos that do not contain an audio stream.")
    print("=" * 60)


if __name__ == "__main__":
    # Execute metadata extraction routine
    extract_metadata()
